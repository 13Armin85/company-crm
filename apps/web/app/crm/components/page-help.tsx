export function guideForPath(pathname: string): Guide {
  if (pathname.startsWith("/portal/requests/"))
    return guide(
      "جزئیات درخواست مشتری",
      "گفت‌وگو و وضعیت یک درخواست پشتیبانی.",
      "پیام‌ها و وضعیت را بررسی کنید.",
      "در صورت نیاز پاسخ یا فایل تکمیلی بفرستید."
    );
  if (pathname.startsWith("/leave-requests/"))
    return guide(
      "جزئیات درخواست مرخصی",
      "پیش‌نمایش، وضعیت و تاریخچهٔ یک درخواست مرخصی.",
      "فرم و مدت را بررسی کنید.",
      "در صورت نیاز، درخواست را امضا یا اصلاح کنید و وضعیت گردش آن را دنبال کنید."
    );
  if (pathname.startsWith("/reports/"))
    return guide(
      "جزئیات گزارش",
      "نمای داده‌ها و نتایج یک گزارش.",
      "فیلترها و بازهٔ زمانی را انتخاب کنید.",
      "نتیجه را بررسی کنید و در صورت مجوز تنظیمات گزارش را ویرایش کنید."
    );
  if (/^\/roles\/[^/]+\/permissions/.test(pathname))
    return guide(
      "مجوزهای نقش",
      "تعیین دسترسی‌های یک نقش سازمانی.",
      "گروه مجوز را باز کنید و موارد لازم را انتخاب کنید.",
      "تغییرات را ذخیره کنید و اثر آن را برای کاربران دارای این نقش بررسی کنید."
    );
  if (pathname.startsWith("/team/"))
    return guide(
      "پروفایل عضو تیم",
      "اطلاعات، نقش‌ها و دسترسی‌های یک کاربر.",
      "تب موردنظر را باز کنید.",
      "در صورت مجوز، تغییرات عضویت یا دسترسی را ذخیره کنید."
    );
  if (pathname.startsWith("/projects/"))
    return guide(
      "جزئیات پروژه",
      "کارها، اعضا و تنظیمات پروژه.",
      "تب موردنظر را انتخاب کنید.",
      "کارها را باز یا ایجاد کنید و وضعیت آن‌ها را پیگیری کنید."
    );
  if (pathname.startsWith("/entities/"))
    return guide(
      "صفحهٔ داده",
      "ثبت و نمایش رکوردهای این نوع داده.",
      "از جستجو، فیلتر و تب‌های جدول برای یافتن رکورد استفاده کنید.",
      "ردیف را باز کنید تا جزئیات یا فرم ویرایش را ببینید.",
      "اگر مجوز طراحی دارید، نما، ستون‌ها و فرم را از ابزارهای همین صفحه تنظیم کنید."
    );
  if (pathname.startsWith("/edit/"))
    return guide(
      "ویرایش رکورد",
      "تغییر اطلاعات ثبت‌شده در فرم.",
      "ورودی‌های لازم را تکمیل یا اصلاح کنید.",
      "تغییرات را ذخیره کنید و نتیجه را در صفحهٔ رکورد بررسی کنید."
    );
  if (pathname === "/entities")
    return guide(
      "همهٔ صفحه‌ها",
      "فهرست صفحه‌ها و نوع داده‌های تعریف‌شده.",
      "صفحهٔ موردنظر را انتخاب کنید.",
      "برای ساخت یا تغییر صفحه، از ابزارهای طراحی با مجوز مناسب استفاده کنید."
    );
  const key = Object.keys(guides)
    .filter((path) => path !== "/" && (pathname === path || pathname.startsWith(`${path}/`)))
    .reduce<string | undefined>((best, path) => (!best || path.length > best.length ? path : best), undefined);
  return (
    guides[key ?? pathname] ??
    guide(
      "این صفحه",
      "نمایش اطلاعات و کارهای مرتبط با این بخش.",
      "اطلاعات صفحه را بررسی کنید.",
      "از دکمه‌ها و فیلترهای همان بخش برای انجام کار استفاده کنید."
    )
  );
}

export function PageHelp() {
  const { pathname } = useLocation();
  const [open, setOpen] = useState(false);
  const triggerRef = useRef<HTMLButtonElement>(null);
  const closeRef = useRef<HTMLButtonElement>(null);
  useEffect(() => setOpen(false), [pathname]);
  useEffect(() => {
    if (!open) return;
    closeRef.current?.focus();
    const close = (event: KeyboardEvent) => {
      if (event.key === "Escape") setOpen(false);
    };
    window.addEventListener("keydown", close);
    const trigger = triggerRef.current;
    return () => {
      window.removeEventListener("keydown", close);
      trigger?.focus();
    };
  }, [open]);
  const current = guideForPath(pathname);
  return (
    <>
      <button
        ref={triggerRef}
        type="button"
        className="icon-button page-help-trigger"
        aria-label={`راهنمای صفحهٔ ${current.title}`}
        title="راهنمای این صفحه"
        aria-expanded={open}
        onClick={() => setOpen(true)}
      >
        <CircleHelp size={19} aria-hidden="true" />
      </button>
      {open &&
        typeof document !== "undefined" &&
        createPortal(
          <div
            className="page-help-layer"
            role="presentation"
            onMouseDown={(event) => {
              if (event.target === event.currentTarget) setOpen(false);
            }}
          >
            <section
              className="page-help-panel"
              role="dialog"
              aria-modal="true"
              aria-labelledby="page-help-title"
              dir="rtl"
            >
              <header className="page-help-header">
                <div className="page-help-heading">
                  <span className="page-help-mark" aria-hidden="true">
                    <CircleHelp size={24} />
                  </span>
                  <div>
                    <small>راهنمای این صفحه</small>
                    <h2 id="page-help-title">{current.title}</h2>
                  </div>
                </div>
                <button
                  ref={closeRef}
                  type="button"
                  className="icon-button"
                  aria-label="بستن راهنما"
                  onClick={() => setOpen(false)}
                >
                  <X size={18} />
                </button>
              </header>
              <div className="page-help-content">
                <section className="page-help-purpose" aria-labelledby="page-help-purpose-title">
                  <div className="page-help-section-heading">
                    <BookOpen size={19} aria-hidden="true" />
                    <h3 id="page-help-purpose-title">این صفحه چه کاری انجام می‌دهد؟</h3>
                  </div>
                  <p>{current.purpose}</p>
                </section>
                <section className="page-help-steps" aria-labelledby="page-help-steps-title">
                  <div className="page-help-section-heading">
                    <h3 id="page-help-steps-title">روش استفاده</h3>
                    <span>{current.steps.length.toLocaleString("fa-IR")} گام</span>
                  </div>
                  <ol>
                    {current.steps.map((step) => (
                      <li key={step}>{step}</li>
                    ))}
                  </ol>
                </section>
              </div>
              <footer className="page-help-footer">
                <button type="button" className="button button-primary" onClick={() => setOpen(false)}>
                  متوجه شدم
                </button>
              </footer>
            </section>
          </div>,
          document.body
        )}
    </>
  );
}
