foreach ($svgAsset in @('apps/space/app/assets/plane-logo.svg', 'apps/admin/app/assets/logos/takeoff-icon-dark.svg', 'apps/admin/app/assets/logos/takeoff-icon-light.svg')) {
    [System.IO.File]::WriteAllText((Join-Path $brandingRepoRoot $svgAsset), $symbolSvg + "`n", $brandingUtf8)
}
$brandingVersion = (Get-FileHash -LiteralPath $symbolMaster -Algorithm SHA256).Hash.Substring(0,12).ToLowerInvariant()
