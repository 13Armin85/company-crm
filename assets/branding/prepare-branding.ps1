param()
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$brandingRepoRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$brandingAssets = Join-Path $brandingRepoRoot 'assets/branding'
$brandingUtf8 = [System.Text.UTF8Encoding]::new($false)

function Write-BrandImage([string]$Source, [string]$Target, [int]$Width, [int]$Height, [double]$Padding = 0) {
    $sourceImage = [System.Drawing.Bitmap]::new($Source)
    $targetImage = [System.Drawing.Bitmap]::new($Width, $Height, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $graphics = [System.Drawing.Graphics]::FromImage($targetImage)
    try {
        $graphics.Clear([System.Drawing.Color]::Transparent)
        $graphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
        $graphics.CompositingQuality = [System.Drawing.Drawing2D.CompositingQuality]::HighQuality
        $graphics.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
        $scale = [Math]::Min(($Width * (1 - 2 * $Padding)) / $sourceImage.Width, ($Height * (1 - 2 * $Padding)) / $sourceImage.Height)
        $imageWidth = $sourceImage.Width * $scale
        $imageHeight = $sourceImage.Height * $scale
        $destination = [System.Drawing.RectangleF]::new(($Width - $imageWidth) / 2, ($Height - $imageHeight) / 2, $imageWidth, $imageHeight)
        $graphics.DrawImage($sourceImage, $destination)
        $null = New-Item -ItemType Directory -Path (Split-Path -Parent $Target) -Force
        $targetImage.Save($Target, [System.Drawing.Imaging.ImageFormat]::Png)
    } finally {
        $graphics.Dispose()
        $targetImage.Dispose()
        $sourceImage.Dispose()
    }
}

function Write-BrandIco([string]$Target) {
    $images = @(16, 32, 48, 256) | ForEach-Object {
        $temporaryPng = Join-Path $brandingAssets "icon-$_.png"
        Write-BrandImage (Join-Path $brandingAssets 'amard-symbol.png') $temporaryPng $_ $_ 0.04
        [PSCustomObject]@{Size=$_;Bytes=[System.IO.File]::ReadAllBytes($temporaryPng)}
    }
    $stream = [System.IO.MemoryStream]::new()
    $writer = [System.IO.BinaryWriter]::new($stream)
    try {
        $writer.Write([UInt16]0)
        $writer.Write([UInt16]1)
        $writer.Write([UInt16]$images.Count)
        $offset = 6 + 16 * $images.Count
        foreach ($entry in $images) {
            $iconDimension = if ($entry.Size -eq 256) { 0 } else { $entry.Size }
            $writer.Write([byte]$iconDimension)
            $writer.Write([byte]$iconDimension)
            $writer.Write([byte]0)
            $writer.Write([byte]0)
            $writer.Write([UInt16]1)
            $writer.Write([UInt16]32)
            $writer.Write([UInt32]$entry.Bytes.Length)
            $writer.Write([UInt32]$offset)
            $offset += $entry.Bytes.Length
        }
        foreach ($entry in $images) { $writer.Write([byte[]]$entry.Bytes) }
        [System.IO.File]::WriteAllBytes($Target, $stream.ToArray())
    } finally { $writer.Dispose(); $stream.Dispose() }
}

