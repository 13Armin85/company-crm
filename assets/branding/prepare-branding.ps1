$brandingCode = @"
// Generated by assets/branding/prepare-branding.ps1. Do not edit image data manually.
export const COMPANY_LOGO_ALT = "$companyLogoAlt";
export const COMPANY_BRAND_VERSION = "$brandingVersion";
export const COMPANY_LOGO_SYMBOL: string = "data:image/png;base64,$symbolData";
